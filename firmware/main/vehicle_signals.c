static const vehicle_signal_t g_unknown = {
    SIG_NONE, "не назначен", 0, SRC_NONE, 0, 0, 0, ""
};

const vehicle_signal_t *vehicle_signals(void)
{
    return g_signals;
}

size_t vehicle_signals_count(void)
{
    return sizeof(g_signals) / sizeof(g_signals[0]);
}

const vehicle_signal_t *vehicle_signal(vehicle_signal_id_t id)
{
    for (size_t i = 0; i < vehicle_signals_count(); ++i) {
        if (g_signals[i].id == id)
            return &g_signals[i];
    }
    return &g_unknown;
}
