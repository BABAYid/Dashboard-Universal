// ============================================================================
//  inputs_analog.h — аналоговые входы AIN0…AIN3 (внешний АЦП ADS1115, I2C-1).
//
//  Зачем внешний АЦП: у ESP32 встроенный АЦП заметно нелинеен (особенно
//  ближе к 3.3 В), а уровень топлива и температура требуют повторяемости.
//  ADS1115 — 16 бит, опорное напряжение своё, результат в милливольтах.
//
//  Каждый вход приходит через делитель 130 кОм / 27 кОм (коэффициент 5.81)
//  и защиту SMBJ3.3A, то есть модуль измеряет 0…2.5 В, а на контакте разъёма
//  это 0…14.5 В. Модуль отдаёт наружу милливольты НА КОНТАКТЕ РАЗЪЁМА —
//  именно то, что нужно для калибровки по датчику.
// ============================================================================
#pragma once

#include <stdbool.h>
#include <stdint.h>

#include "esp_err.h"

// Настройка шины I2C-1 и проверка связи с ADS1115.
esp_err_t inputs_analog_init(void);

// Опрос: за один вызов читается результат предыдущего канала и запускается
// следующий. Полный круг по четырём каналам — 4 × ANALOG_PERIOD_MS.
void inputs_analog_update(void);

// Напряжение на контакте разъёма, мВ (с учётом делителя и усреднения).
// channel — 0…AIN_COUNT-1 (AIN0…AIN3, как на схеме).
uint16_t analog_mv(uint8_t channel);

// Сырой код АЦП последнего отсчёта (0…32767 при усилении ±4.096 В) —
// для отладки и калибровки.
int16_t analog_raw(uint8_t channel);

// Отвечает ли ADS1115. Если нет — значения аналоговых датчиков недостоверны.
bool inputs_analog_ok(void);

// Сколько раз не удалось прочитать АЦП (насыщается на 255) — для диагностики.
uint8_t inputs_analog_errors(void);
