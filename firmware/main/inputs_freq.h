// ============================================================================
//  inputs_freq.h — частотные входы: спидометр, тахометр, сигнал расхода.
//
//  Отдельных «частотных» ножек на плате нет — частота меряется на тех же
//  дискретных входах DIN_n, которые в таблице проводов помечены как SRC_FREQ.
//  Внутри: прерывание по спаду (сигнал 12 В сажает вход на землю), замер
//  периода между импульсами и перевод в герцы.
//
//  Почему период, а не счёт импульсов за окно: на малой скорости импульсов
//  за 50 мс приходит единицы, и счёт даёт ошибку в десятки процентов, а
//  период измеряется точно всегда. При пропадании импульсов (машина встала)
//  частота обнуляется по таймауту FREQ_TIMEOUT_MS.
// ============================================================================
#pragma once

#include <stdbool.h>
#include <stdint.h>

#include "esp_err.h"

#define FREQ_CHANNELS_MAX   4

// Настраивает выводы, объявленные в таблице проводов как SRC_FREQ,
// и вешает обработчики прерываний. Возвращает ESP_OK, даже если частотных
// входов нет вообще (это штатная ситуация до заполнения таблицы).
esp_err_t inputs_freq_init(void);

// Пересчёт частоты по измеренным периодам. Вызывать каждые FREQ_PERIOD_MS.
void inputs_freq_update(void);

// Частота на входе DIN_n, Гц. 0, если импульсов нет дольше FREQ_TIMEOUT_MS
// или вход не назначен частотным.
float inputs_freq_hz(uint8_t channel);

// Сколько всего импульсов пришло на вход с момента запуска — нужно для
// интегрирования расхода топлива и для проверки проводки на столе.
uint32_t inputs_freq_pulses(uint8_t channel);

// Сколько входов настроено как частотные (для журнала запуска).
int inputs_freq_channel_count(void);
