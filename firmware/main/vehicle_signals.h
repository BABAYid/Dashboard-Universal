// ============================================================================
//  vehicle_signals.h — таблица «провод машины → вход платы → смысл сигнала».
//
//  ЭТО ЕДИНСТВЕННЫЙ ФАЙЛ, который правят, когда уточняется список проводов
//  от старой приборки. Прошивка везде работает через него, поэтому добавление
//  провода не требует правок в драйверах, кадрах CAN и задачах.
//
//  ─── Что нужно знать про входы платы (из «Схема принципиальная.pdf») ───────
//
//  1. ДИСКРЕТНЫЕ ВХОДЫ DIN_1…DIN_23 рассчитаны на сигнал «плюс 12 В».
//     Схема входа: провод → 1 кОм → светодиод оптопары → земля ПЛАТЫ.
//     То есть вход срабатывает, когда на проводе появляется +12 В
//     относительно массы автомобиля. Провод, который замыкается на массу
//     (ручник, аварийное давление масла, ремень, концевики), так подключить
//     нельзя: светодиод оптопары просто не зажжётся.
//     Для таких проводов нужна переделка канала: катод светодиода отрезать
//     от земли платы и завести на провод машины, а анод через 1 кОм — на +12 В.
//     Это две перемычки на канал (резать дорожку и два провода).
//
//  2. АНАЛОГОВЫЕ ВХОДЫ AIN0…AIN3 — делитель 130 кОм / 27 кОм (коэффициент
//     5.81) с защитой SMBJ3.3A на модуле ADS1115. Вход рассчитан на
//     ИСТОЧНИК НАПРЯЖЕНИЯ 0…12 В (для канала газа в схеме помечено «ЛИНИЯ 5В»).
//     Датчик-реостат (уровень топлива) и терморезистор (температура) дают
//     не напряжение, а сопротивление на массу: чтобы такая схема заработала,
//     на провод нужно подать питание через резистор-подтяжку, иначе измерять
//     нечего. Подтяжка ставится либо на плате (переделка), либо внешним
//     резистором от +5 В/стабилизированного питания к проводу датчика.
//
//  3. ЧАСТОТНЫЕ входы (спидометр, тахометр, сигнал расхода) — те же
//     дискретные входы, частота считается программно. Оптопара PC817 с
//     подтяжкой 10 кОм держит примерно до 20 кГц: спидометру и тахометру
//     хватает с запасом.
//
//  ─── Что прислать, чтобы заполнить таблицу ────────────────────────────────
//  По каждому проводу старой приборки: контакт разъёма, что это за сигнал,
//  и КАК ОН РАБОТАЕТ электрически (плюс 12 В при срабатывании / замыкание
//  на массу / меняющееся сопротивление / напряжение 0…5 В).
//  Пункт «как работает» важнее названия: именно от него зависит, можно ли
//  вешать провод на эту плату напрямую.
// ============================================================================
#pragma once

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

// ---------------------------------------------------------------------------
//  Источник сигнала
// ---------------------------------------------------------------------------
typedef enum {
    SRC_NONE = 0,   // провод не назначен (ждём список проводов)
    SRC_DIN,        // дискретный вход DIN_1…DIN_15 (напрямую в ESP32)
    SRC_PCF,        // дискретный вход DIN_16…DIN_23 (через PCF8574, I2C)
    SRC_AIN,        // аналоговый вход AIN0…AIN3 (ADS1115)
    SRC_FREQ,       // частотный вход (тот же DIN_n, но меряется частота)
} signal_source_t;

// ---------------------------------------------------------------------------
//  Смысл сигнала. Значения протокола собираются из этих сигналов.
// ---------------------------------------------------------------------------
typedef enum {
    SIG_NONE = 0,

    // 0x200, байт 0 — свет
    SIG_LEFT_TURN,
    SIG_RIGHT_TURN,
    SIG_HIGH_BEAM,
    SIG_LOW_BEAM,
    SIG_POSITION_LIGHTS,
    SIG_FOG_LIGHTS,
    SIG_REVERSE,
    SIG_BRAKE,

    // 0x200, байт 1 — индикаторы состояния
    SIG_CHECK_ENGINE,
    SIG_ABS,
    SIG_HAND_BRAKE,
    SIG_SEAT_BELT,
    SIG_OIL_PRESSURE,
    SIG_GEAR_LOCK,

    // 0x400 — АКПП
    SIG_GEAR_P,
    SIG_GEAR_R,
    SIG_GEAR_N,
    SIG_GEAR_D,
    SIG_GEAR_S1,
    SIG_GEAR_S2,

    // 0x500 — газ
    SIG_GAS_MODE,       // переключатель топлива «газ» (дискретный)
    SIG_GAS_LEVEL,      // напряжение датчика уровня газа 0…5 В (аналоговый)

    // 0x100 — движение (частотные входы)
    SIG_SPEED,
    SIG_RPM,
    SIG_FUEL_RATE,      // сигнал расхода от ЭБУ, если он есть в проводке

    // 0x300 — аналоговые датчики
    SIG_ENGINE_TEMP,
    SIG_FUEL_LEVEL,
    SIG_BATTERY_VOLTAGE,
    SIG_OUTSIDE_TEMP,

    // Служебное
    SIG_IGNITION,       // зажигание (ACC): по нему блок уходит в сон
    SIG_LOW_BEAM_SENSE, // (резерв на будущее)

    SIG_COUNT
} vehicle_signal_id_t;

// ---------------------------------------------------------------------------
//  Описание одного сигнала
// ---------------------------------------------------------------------------
typedef struct {
    vehicle_signal_id_t id;
    const char *name;        // человеческое имя — попадает в лог
    uint8_t     x1_pin;      // контакт разъёма X1 (справочно, из схемы)
    uint8_t     source;      // signal_source_t
    uint8_t     channel;     // DIN_n / AIN_n / частотный канал
    uint8_t     flags;       // SIG_FLAG_*
    uint16_t    debounce_ms; // антидребезг для дискретных входов
    const char *note;        // требование к электрике провода
} vehicle_signal_t;

// Дискретный сигнал нужно инвертировать, если провод замыкается на массу
// (срабатывание = 0 на входе). На этой плате все входы активны низким уровнем,
// инверсия уже учтена в inputs_digital.c, а этот флаг — про сам провод машины:
// с ним сигнал читается «замыкание на массу», а не «плюс 12 В».
// ВНИМАНИЕ: без переделки канала (см. шапку файла) такой провод физически
// не может зажечь оптопару — флаг работает только после переделки.
#define SIG_FLAG_GROUND_SWITCHED   (1u << 0)

// Таблица целиком (заканчивается строкой с id = SIG_NONE).
const vehicle_signal_t *vehicle_signals(void);
size_t vehicle_signals_count(void);

// Описание сигнала по его смыслу (никогда не NULL — для неназначенного
// сигнала возвращает запись с source = SRC_NONE).
const vehicle_signal_t *vehicle_signal(vehicle_signal_id_t id);

// Назначен ли сигнал на конкретный вход.
static inline bool vehicle_signal_assigned(vehicle_signal_id_t id)
{
    return vehicle_signal(id)->source != SRC_NONE;
}
