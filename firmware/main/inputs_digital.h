// ============================================================================
//  inputs_digital.h — дискретные входы 12 В: DIN_1…DIN_23.
//
//  DIN_1…DIN_15  — оптопара садится прямо на вывод ESP32 (см. board_pins.h);
//  DIN_16…DIN_23 — оптопара садится на PCF8574 (I2C-2, адрес 0x20).
//
//  Все входы платы АКТИВНЫ НИЗКИМ УРОВНЕМ: сигнал 12 В на проводе сажает
//  вывод на землю. Наружу этот модуль отдаёт привычное «true = сигнал есть»,
//  инверсия живёт только здесь.
// ============================================================================
#pragma once

#include <stdbool.h>
#include <stdint.h>

#include "esp_err.h"

#define DIN_CHANNELS        23      // DIN_1…DIN_23 (нумерация как на схеме, с 1)
#define DIN_DIRECT_COUNT    15      // DIN_1…DIN_15 — напрямую в ESP32
#define DIN_PCF_COUNT       8       // DIN_16…DIN_23 — через PCF8574

// Настройка выводов и запуск шины I2C-2. Возвращает ошибку, если PCF8574
// не ответил (это не смертельно: первые 15 входов продолжат работать).
esp_err_t inputs_digital_init(void);

// Опрос всех входов. Вызывать периодически, период — INPUTS_PERIOD_MS.
// Внутри: чтение выводов ESP32, чтение PCF8574 по I2C и антидребезг.
void inputs_digital_update(void);

// Состояние входа после антидребезга: true = сигнал есть.
// channel — 1…23 (DIN_n, как на схеме). Вне диапазона → false.
bool din_signal(uint8_t channel);

// Сырое состояние входа (без антидребезга) — для отладки и замеров.
bool din_raw(uint8_t channel);

// Сырые битовые карты для журнала отладки: бит (n-1) — DIN_n.
uint16_t din_bitmap_direct(void);   // DIN_1…DIN_15 (младшие 15 бит)
uint8_t din_bitmap_pcf(void);       // DIN_16…DIN_23 (бит 0 — DIN_16)

// Отвечает ли PCF8574 (для диагностики: если нет, входы 16…23 недостоверны).
bool inputs_digital_pcf_ok(void);

// Число ошибок обмена по I2C-2 (насыщается на 255) — уходит в кадр статуса.
uint8_t inputs_digital_i2c_errors(void);
