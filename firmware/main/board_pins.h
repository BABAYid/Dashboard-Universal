// ============================================================================
//  board_pins.h — «паспорт» платы блока сбора.
//
//  ЕДИНСТВЕННОЕ место в прошивке, где встречаются номера выводов ESP32.
//  Всё остальное (разбор сигналов, кадры CAN) работает с именами DIN_n/AIN_n.
//
//  Источник: «Схема принципиальная.pdf» (Altium, 13.10.2026, файлы
//  ESP-32.SchDoc, CAN_ISO_BUFFERS.SchDoc, ADC.SchDoc, OPTO.SchDoc,
//  POWER.SchDoc, CONNECTORS.SchDoc) и папка rezonit/ (Gerber, 08.09.2026).
//
//  Плата — носитель модулей, размер 175x120 мм:
//    • ESP32 DevKit V1 (30 выводов) в разъёмах;
//    • SN65HVD230 — CAN-трансивер (модуль);
//    • ADS1115 — 4 аналоговых входа (модуль, I2C);
//    • PCF8574 — расширитель на 8 входов (I2C, адрес 0x20);
//    • MP1584EN + AMS1117 — питание 12 В → 5 В → 3.3 В;
//    • MC33290 + SN74LVC2T45 — K-линия (ISO 9141, «ISO» в разъёме);
//    • GY-GPSV3-NEO-M8N — GPS (см. оговорку ниже);
//    • 23 оптопары PC817 с ТВС SMBJ12A — дискретные входы 12 В.
//
//  Дискретные входы АКТИВНЫ НИЗКИМ УРОВНЕМ: сигнал 12 В приходит на вход,
//  светодиод оптопары зажигается, фототранзистор сажает вывод ESP32 на землю
//  (подтяжка 10 кОм на +3.3 В стоит на плате). То есть «вход сработал» —
//  это логический 0 на выводе. Инверсия спрятана в inputs_digital.c,
//  наружу сигналы отдаются как «1 = сигнал есть».
// ============================================================================
#pragma once

#include "driver/gpio.h"

// ---------------------------------------------------------------------------
//  CAN (TWAI) — SN65HVD230
// ---------------------------------------------------------------------------
#define PIN_CAN_TX              GPIO_NUM_18   // header 24
#define PIN_CAN_RX              GPIO_NUM_5    // header 23

// ---------------------------------------------------------------------------
//  I2C-1 — ADS1115 (4 аналоговых входа)
// ---------------------------------------------------------------------------
#define PIN_I2C1_SDA            GPIO_NUM_21   // header 26
#define PIN_I2C1_SCL            GPIO_NUM_22   // header 29
#define I2C1_ADDR_ADS1115       0x48          // ADDR на GND

// ---------------------------------------------------------------------------
//  I2C-2 — PCF8574 (DIN_16…DIN_23)
//
//  ВНИМАНИЕ, ГРАБЛИ ПЛАТЫ: линия SDA сидит на GPIO12 (MTDI). Это strapping-
//  вывод: если в момент включения на нём высокий уровень, ESP32 переключает
//  питание флеш-памяти на 1.8 В и модуль не стартует. На плате на SDA стоит
//  подтяжка 4.7 кОм на +3.3 В (R3), то есть при штатной сборке модуль не
//  запустится. Лечится без переделки платы:
//      • резистор подтяжки на линии SDA (R3, 4.7 кОм) НЕ запаивать;
//      • подтяжку SDA включить программно (внутренняя ~45 кОм) в i2c_init().
//  При 100 кГц и коротких проводках внутри платы этого достаточно.
//  На линии SCL (GPIO14) подтяжка 4.7 кОм (R4) безопасна — оставить.
// ---------------------------------------------------------------------------
#define PIN_I2C2_SDA            GPIO_NUM_12   // header 12  (см. грабли выше)
#define PIN_I2C2_SCL            GPIO_NUM_14   // header 11
#define I2C2_ADDR_PCF8574       0x20          // A0/A1/A2 на GND
#define PCF8574_SDA_NEEDS_INTERNAL_PULLUP  1  // см. грабли выше

// ---------------------------------------------------------------------------
//  Дискретные входы напрямую в ESP32: DIN_1 … DIN_15
//  (оптопара DK1…DK15, на выводе — активный ноль)
// ---------------------------------------------------------------------------
#define PIN_DIN_1               GPIO_NUM_36   // header  2  SENSOR_VP, только вход
#define PIN_DIN_2               GPIO_NUM_39   // header  3  SENSOR_VN, только вход
#define PIN_DIN_3               GPIO_NUM_34   // header  4  только вход
#define PIN_DIN_4               GPIO_NUM_35   // header  5  только вход
#define PIN_DIN_5               GPIO_NUM_32   // header  6
#define PIN_DIN_6               GPIO_NUM_33   // header  7
#define PIN_DIN_7               GPIO_NUM_25   // header  8
#define PIN_DIN_8               GPIO_NUM_26   // header  9
#define PIN_DIN_9               GPIO_NUM_27   // header 10
#define PIN_DIN_10              GPIO_NUM_13   // header 13
#define PIN_DIN_11              GPIO_NUM_23   // header 30
#define PIN_DIN_12              GPIO_NUM_19   // header 25
#define PIN_DIN_13              GPIO_NUM_4    // header 20
#define PIN_DIN_14              GPIO_NUM_2    // header 19
#define PIN_DIN_15              GPIO_NUM_15   // header 18

// ---------------------------------------------------------------------------
//  Служебные линии
// ---------------------------------------------------------------------------
#define PIN_UART2_TX            GPIO_NUM_17   // header 22  K-линия, передача
#define PIN_UART2_RX            GPIO_NUM_16   // header 21  K-линия, приём
#define PIN_UART0_TX            GPIO_NUM_1    // header 28  GPS RX + консоль
#define PIN_UART0_RX            GPIO_NUM_3    // header 27  GPS TX + консоль

// Развилка DIN_1 / ADC_ALERT на выводе GPIO36 (перемычки R1 и R2, обе 0 Ом).
// Запаивают ровно одну:
//   • запаян R2 → на GPIO36 приходит DIN_1 (штатный вариант, 23 дискретных входа);
//   • запаян R1 → на GPIO36 приходит ALRT от ADS1115 (прерывание «данные готовы»),
//     и тогда дискретных входов 22, а DIN_1 не используется.
#define JUMPER_R1_ADC_ALERT_FITTED  0

// ---------------------------------------------------------------------------
//  Аналоговые входы: ADS1115, каналы A0…A3 (разъём X1)
// ---------------------------------------------------------------------------
//  Каждый вход приходит через делитель 130 кОм / 27 кОм (коэффициент 5.81)
//  и защиту SMBJ3.3A. Для канала газа (AIN3) в схеме помечено «ЛИНИЯ 5В».
#define AIN_0                   0
#define AIN_1                   1
#define AIN_2                   2
#define AIN_3                   3
#define AIN_COUNT               4

// ---------------------------------------------------------------------------
//  Частотные входы (спидометр, тахометр)
// ---------------------------------------------------------------------------
//  Отдельных «частотных» выводов на плате нет: частоту меряем на любом
//  дискретном входе (в схеме это те же оптопары). Какой DIN_n какой —
//  задаётся в vehicle_signals.h. Ограничение: оптопара PC817 с подтяжкой
//  10 кОм держит примерно до 20 кГц — для датчика скорости и тахометра
//  с запасом, но для сигнала расхода топлива от ЭБУ (если он есть) надо
//  проверять частоту на машине.
#define FREQ_MAX_CHANNELS       4

