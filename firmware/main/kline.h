// ============================================================================
//  kline.h — K-линия: диагностика ЭБУ (пока только пассивный сниффер).
//
//  Зачем сниффер. ЭБУ одной и той же машины может говорить по K-линии тремя
//  разными протоколами: KWP1281 (старый VAG), KWP2000 (он же OBD-II по
//  K-линии) или ISO 9141 с блоками измерений. От протокола зависит весь код
//  чтения данных, а узнать его можно только на машине. Поэтому сначала —
//  пассивный сниффер: блок ничего не передаёт в линию, а показывает в консоли
//  всё, что по ней идёт, пока работает штатный диагностический сканер.
//
//  Полученный дамп — это и есть задание на протокол: по нему видно и скорость,
//  и инициализацию, и структуру блоков, и адрес ЭБУ.
// ============================================================================
#pragma once

#include <stdbool.h>
#include <stdint.h>

#include "esp_err.h"

// Поднять UART2 на K-линии. Если сниффер выключен в config.h — ничего не делает.
esp_err_t kline_init(void);

// Забрать из UART всё, что пришло, и показать в консоли. Вызывать часто
// (например, из задачи входов каждые 20 мс).
void kline_poll(void);

// Включён ли сниффер (для журнала запуска).
bool kline_enabled(void);

// Сколько байт принято с K-линии — показывает, есть ли вообще жизнь на линии.
uint32_t kline_bytes_seen(void);
