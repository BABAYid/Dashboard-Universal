// ============================================================================
//  twai_bus.h — шина CAN блока сбора (контроллер TWAI внутри ESP32).
//
//  Шина отдельная: только ESP32 и приборка (RK3588). Скорость 500 кбит/с,
//  согласующие резисторы 120 Ом на обоих концах (см. esp32_wiring.txt).
//  Трансивер — модуль SN65HVD230 на 3.3 В.
// ============================================================================
#pragma once

#include <stdbool.h>
#include <stdint.h>

#include "esp_err.h"

#define CAN_BITRATE_KBPS    500

// Поднять драйвер TWAI. Возвращает ошибку, если драйвер не установился.
esp_err_t twai_bus_init(void);

// Отправить кадр. true — кадр ушёл в контроллер (не значит «принят приборкой»:
// подтверждение приходит от второго узла шины, см. twai_bus_error_count()).
bool twai_bus_send(uint32_t id, const uint8_t data[8]);

// Периодический вызов: следит за состоянием контроллера и поднимает шину
// после bus-off (обрыв провода, выключенная приборка на столе).
void twai_bus_poll(void);

// Счётчик ошибок шины для кадра 0x7F0 (насыщается на 255).
uint8_t twai_bus_error_count(void);

// Сколько кадров отправлено с момента запуска — для журнала отладки.
uint32_t twai_bus_frames_sent(void);

// Текущее состояние контроллера словами (для журнала).
const char *twai_bus_state_name(void);
