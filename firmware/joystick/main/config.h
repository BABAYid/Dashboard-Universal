// ============================================================================
//  config.h — настройки модуля ввода «джойстик BMW iDrive» (F20/F30).
//
//  Всё, что зависит от платы и от кабеля, собрано здесь: номера выводов,
//  периоды, приоритеты задач и номера кадров. В остальных файлах номеров
//  выводов нет — чтобы при переносе на другую плату править одно место.
// ============================================================================
#pragma once

// ---------------------------------------------------------------------------
//  CAN (TWAI) — трансивер SN65HVD230 (или любой 3.3-вольтовый CAN-трансивер)
// ---------------------------------------------------------------------------
//  Пара GPIO 5 / GPIO 4 взята из проекта селектора АКПП
//  (PlatformIO/Projects/AKPP_Selector): там джойстик BMW уже работал на этой
//  паре выводов, а на DevKit V1 они выведены рядом с землёй и +3.3 В — удобно
//  для модуля трансивера. GPIO5 — strapping-вывод, но он занят передатчиком,
//  а передатчик начинает работать уже после загрузки, когда загрузчик этот
//  вывод больше не смотрит.
#define PIN_CAN_TX              5
#define PIN_CAN_RX              4

#define CAN_BITRATE_KBPS        500   // общая шина с блоком сбора и приборкой

// ---------------------------------------------------------------------------
//  Задачи и очереди
// ---------------------------------------------------------------------------
//  Приём приоритетнее передачи: потерянный кадр 0x267 — это потерянное
//  нажатие, которое восстановить нечем, а лишние 10 мс в очереди heartbeat
//  или события 0x530 никто не заметит.
#define APP_TASK_PRIORITY_CAN_RX    7
#define APP_TASK_PRIORITY_CAN_TX    6
#define APP_TASK_STACK_CAN          4096

//  Очередь на отправку фиксированного размера, без malloc на горячем пути.
//  24 кадра — это запас на «прокрутку» энкодера рывком плюс пачку событий,
//  пока шина занята кадрами блока сбора.
#define CAN_TX_QUEUE_LEN        24
#define CAN_TX_TICK_MS          10    // ожидание кадра из очереди в задаче передачи
#define CAN_RX_WAIT_MS          20    // таймаут приёма: задача не висит вечно

// ---------------------------------------------------------------------------
//  Жизнеобеспечение джойстика
// ---------------------------------------------------------------------------
//  Модуль BMW засыпает, если не видит своих кадров, поэтому heartbeat
//  отправляется всегда, независимо от того, трогают джойстик или нет.
#define JOY_HEARTBEAT_MS        100
#define JOY_WAKE_RETRY_MS       2000  // тишина от джойстика = повод разбудить
#define JOY_WAKE_LOG_EVERY      15    // логировать каждый 15-й повтор (~30 с)

// ---------------------------------------------------------------------------
//  Идентификаторы кадров шины приборки (can_protocol_v1.4.txt)
// ---------------------------------------------------------------------------
#define CAN_ID_COLLECTOR_LIGHTS 0x200  // лампы и индикаторы, от блока сбора
#define CAN_ID_INPUT_EVENT      0x530  // событие ввода, от нас приборке

// ---------------------------------------------------------------------------
//  Отладка
// ---------------------------------------------------------------------------
#define STATUS_LOG_MS           5000  // период строки со счётчиками

//  Энкодер джойстика: если на конкретном экземпляре поворот вправо приходит
//  со знаком «минус» (список в приборке листается не в ту сторону),
//  поставить 1 — и больше ничего не менять.
#define JOY_ENCODER_INVERT      0

// Версия прошивки — по ней в логе видно, что залито в модуль.
#define FW_VERSION_MAJOR        1
#define FW_VERSION_MINOR        0
