// ============================================================================
//  bmw_joystick.h — протокол джойстика BMW iDrive (F20/F30) и события ввода.
//
//  Модуль BMW — не «кнопочная матрица»: он живой узел CAN, который надо
//  кормить кадрами, иначе он засыпает и перестаёт отдавать нажатия. Отсюда три
//  группы кадров: чем кормим мы, что он отдаёт и что мы из этого делаем.
//
//  Номера кадров и раскладка байтов получены сниффером шины на реальном
//  модуле; они не из документации BMW.
// ============================================================================
#pragma once

#include <stdbool.h>
#include <stdint.h>

// ---------------------------------------------------------------------------
//  Кадры, которые джойстик ждёт ОТ нас
// ---------------------------------------------------------------------------
#define JOY_ID_LIGHT            0x202  // подсветка кнопок, данные FD
#define JOY_ID_HEARTBEAT        0x563  // «я жив», каждые 100 мс
#define JOY_ID_WAKE             0x273  // «проснись» после старта или тишины

// ---------------------------------------------------------------------------
//  Кадры, которые джойстик отдаёт САМ
// ---------------------------------------------------------------------------
#define JOY_ID_EVENT            0x267  // кнопки, направления, нажатие на ручку
#define JOY_ID_ENCODER          0x264  // счётчик поворота
#define JOY_ID_EVENT_ACK        0x5E7  // подтверждение событий — игнорируем

// ---------------------------------------------------------------------------
//  Коды кнопок в кадре 0x530 (can_protocol_v1.5.txt).
//  Порядок и значения — из протокола приборки, не из BMW: у BMW свои
//  «указатели» в байте 5 кадра 0x267, они переводятся в эти коды.
// ---------------------------------------------------------------------------
#define IN_BTN_MENU             0x01
#define IN_BTN_BACK             0x02
#define IN_BTN_OPTION           0x03
#define IN_BTN_RADIO            0x04
#define IN_BTN_MEDIA            0x05
#define IN_BTN_NAV              0x06
#define IN_BTN_TEL              0x07
#define IN_BTN_UP               0x08
#define IN_BTN_DOWN             0x09
#define IN_BTN_LEFT             0x0A
#define IN_BTN_RIGHT            0x0B
#define IN_BTN_PRESS            0x0C

// Вид события в байте 0 кадра 0x530.
#define IN_EVENT_BUTTON         0x01
#define IN_EVENT_ENCODER        0x02

// Разобранное событие ввода — ровно то, что уходит в кадр 0x530.
typedef struct {
    uint8_t kind;   // IN_EVENT_BUTTON / IN_EVENT_ENCODER
    uint8_t code;   // код кнопки для 0x530; для энкодера 0
    int8_t  value;  // кнопка: 1 нажата, 0 отпущена; энкодер: дельта
} input_event_t;

// Сбросить состояние и отправить джойстику «проснись» (0x273).
// Вызывается один раз при старте, когда шина уже поднята.
void joy_init(void);

// Периодический вызов из задачи ПЕРЕДАЧИ: heartbeat 0x563 каждые 100 мс и
// повтор пробуждения, если джойстик молчит дольше 2 секунд.
void joy_periodic(void);

// Разобрать принятый кадр. true — в *event лежит новое событие ввода
// (нажатие/отпускание кнопки или поворот энкодера); false — кадр нам не
// интересен, это повтор или служебный кадр.
//
// Побочный эффект: на фронте «габариты включились» из кадра 0x200 сам
// отправляет 0x202 (подсветку) — но события ввода при этом не выдаёт.
bool joy_handle_frame(uint32_t id, uint8_t dlc, const uint8_t data[8],
                      input_event_t *event);

// Имя кнопки по коду 0x530 — для журнала («кнопка NAV нажата»).
const char *joy_button_name(uint8_t code);
