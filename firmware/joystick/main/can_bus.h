// ============================================================================
//  can_bus.h — шина CAN модуля ввода (контроллер TWAI внутри ESP32).
//
//  На шине три узла: этот модуль, блок сбора приборки и сама приборка.
//  Скорость 500 кбит/с, стандартные 11-битные ID, 8 байт данных — как в
//  can_protocol_v1.5.txt. Согласующие резисторы 120 Ом на концах шины.
//
//  Файл даёт две разные операции отправки, и это не случайность:
//    • can_bus_transmit() — отправить прямо сейчас, из задачи передачи.
//      Так уходят кадры жизнеобеспечения джойстика (0x563, 0x273, 0x202):
//      их период задаёт таймер, и задерживать их приёмом нельзя.
//    • can_bus_send() — положить в очередь и идти дальше. Так уходит 0x530
//      из задачи приёма: событие нельзя терять из-за того, что шина занята.
// ============================================================================
#pragma once

#include <stdbool.h>
#include <stdint.h>

#include "esp_err.h"

#define CAN_FRAME_BYTES 8

// Кадр в очереди на отправку. Копия целиком, без указателей: очередь живёт
// в статическом буфере FreeRTOS, динамического выделения на горячем пути нет.
typedef struct {
    uint32_t id;
    uint8_t  data[CAN_FRAME_BYTES];
} can_frame_t;

// Поднять драйвер TWAI и запустить шину. Повторный вызов безопасен: если
// шина уже работает, вернётся ESP_OK (нужно для повторных попыток в задаче
// передачи, когда модуль стартовал с неподключённым трансивером).
esp_err_t can_bus_init(void);

// Шина поднята и готова принимать кадры в работу.
bool can_bus_is_ready(void);

// Положить кадр в очередь на отправку (не блокируется). false — очередь
// переполнена, кадр потерян (счётчик потерь виден в строке состояния).
bool can_bus_send(uint32_t id, const uint8_t data[CAN_FRAME_BYTES]);

// Отправить кадр немедленно. Только из задачи передачи: внутри короткое
// ожидание (5 мс), чтобы не вставать намертво при плохой шине.
bool can_bus_transmit(uint32_t id, const uint8_t data[CAN_FRAME_BYTES]);

// Взять кадр из очереди на отправку. timeout_ms = 0 — не ждать.
bool can_bus_tx_wait(can_frame_t *frame, uint32_t timeout_ms);

// Принять кадр с шины. false — за timeout_ms ничего не пришло (это норма:
// джойстик молчит, пока его не трогают) или шина не поднята.
bool can_bus_receive(uint32_t *id, uint8_t *dlc, uint8_t data[CAN_FRAME_BYTES],
                     uint32_t timeout_ms);

// Периодический вызов из задачи передачи: следит за состоянием контроллера
// и поднимает шину после bus-off (обрыв провода, выключенная приборка на
// столе, неподключённый джойстик).
void can_bus_poll(void);

// Счётчики для журнала и для диагностики на столе.
uint32_t can_bus_frames_sent(void);
uint32_t can_bus_frames_received(void);
uint32_t can_bus_frames_dropped(void);
uint32_t can_bus_error_count(void);

// Текущее состояние контроллера словами (для журнала).
const char *can_bus_state_name(void);
